/**
 * Ductulator — the duct sizing model, ported from ductulator.py (workbook V1.26).
 *
 * Sizes a duct from any one design criterion, then reports the round duct and
 * the equal-friction rectangular duct that carries the same air at the same
 * friction rate.
 *
 * Round/rectangular conversion uses the Huebscher (1948) circular equivalent
 * adopted by ACCA Manual D Appendix 3 and ASHRAE Fundamentals Ch. 21:
 *
 *     De = 1.30 * (W*H)^0.625 / (W+H)^0.25
 *
 * which holds friction rate and airflow constant — NOT cross-sectional area.
 * The equal-friction rectangle always has more free area than its round
 * equivalent, so it runs at a lower velocity; both velocities are reported.
 *
 * Pressure drop uses one model in both directions, so the calculator is self
 * consistent — sizing on a friction rate and then entering the resulting
 * diameter returns the rate you asked for:
 *   - friction rate from round duct — Swamee-Jain explicit friction factor fed
 *     into Darcy-Weisbach, workbook cells I31:I36.
 *   - round duct from friction rate — that same relation inverted for D,
 *     workbook 'Worksheet' G9:H26.
 *
 * Swamee, P. K., & Jain, A. K. (1976). Explicit equations for pipe-flow
 * problems. Journal of the Hydraulics Division, ASCE, 102(5), 657-664.
 *
 * This is a line-for-line port. JavaScript and Python both compute in IEEE-754
 * doubles, so the two agree bit for bit; check-ductulator.mjs proves it against
 * 576 cases generated by the Python original. Keep them in step: the Python is
 * the reference implementation and is what was validated against the workbook.
 * No dependencies — it runs unchanged in the browser and in Node.
 */

// ---------------------------------------------------------------------------
// Air properties and constants, lifted from the workbook
// ---------------------------------------------------------------------------
export const RHO = 0.0735;          // lb/ft^3       air density            (sheet J28)
export const MU = 3.869e-7;         // lb-sec/ft^2   dynamic viscosity      (sheet I28)
export const GC = 32.2;             // ft/sec^2      gravitational constant (Worksheet D6)

export const PSI_TO_IN_WG = 27.708;              // sheet I36
export const PA_PER_IN_WG = 249.08890833333;

// The workbook's kinematic viscosity (sheet K28, 1.62e-4 ft^2/sec) and its
// 5.197 lbf/ft^2 per in. wg (Worksheet E2) were only used by White's sizing
// solution, which V1.26 replaced; both are intentionally absent here.

// Exact unit conversions. The workbook rounds several of these (fpm per m/s as
// 197 rather than 196.85, ft per m as 3.281); using exact values here shifts
// metric output by <0.1%. See "Deviations from the workbook" in the port's README.
export const FT_PER_M = 3.280839895;
export const IN_PER_M = 39.37007874;
export const CFM_PER_LPS = 2.118880003;
export const FPM_PER_MPS = 196.8503937;

// Reference length the friction rate is quoted over.
export const BASIS_FT = 100.0;      // in. wg per 100 ft
export const BASIS_M = 30.0;        // Pa per 30 m

// Absolute roughness, ft (sheet N27:N30).
export const ROUGHNESS_FT = Object.freeze({
  'Duct board': 1.9e-3,
  'Fabric DurkeeSox': 2.4e-2,
  'Flex': 7.75e-3,
  'Metal': 3.0e-4,
});

export const Units = Object.freeze({ US: 'US', METRIC: 'Metric' });

export const Material = Object.freeze({
  DUCT_BOARD: 'Duct board',
  FABRIC_DURKEESOX: 'Fabric DurkeeSox',
  FLEX: 'Flex',
  METAL: 'Metal',
});

export const Criterion = Object.freeze({
  AIR_VELOCITY: 'Air Velocity',
  FRICTION_LOSS: 'Friction Loss',
  ROUND_DIA: 'Round Duct Dia.',
  RECT_WH: 'Rect. Duct, W x H',
});

// ---------------------------------------------------------------------------
// Round <-> rectangular, per Manual D
// ---------------------------------------------------------------------------

/**
 * Circular equivalent of a W x H rectangular duct; same units in and out.
 * Equal friction rate and equal airflow — not equal area.
 */
export function huebscherDe(w, h) {
  if (w <= 0 || h <= 0) return 0.0;
  return 1.30 * (w * h) ** 0.625 / (w + h) ** 0.25;
}

/**
 * Rectangle carrying the same airflow at the same friction rate as `de` round.
 *
 * With no `height` this returns the square solution, which is exact:
 *     De = 1.30 * a^1.25 / (2a)^0.25 = 1.30 * a / 2^0.25
 *     ->  a = De * 2^0.25 / 1.30
 *
 * With a `height` there is no closed form, so this iterates the fixed point
 *
 *     W = (De * (H + W)^0.25 / 1.30)^1.6 / H
 *
 * a strong contraction (factor ~0.4*W/(H+W) < 0.4) that reaches machine
 * precision in well under 50 passes for any realistic duct.
 *
 * @returns {[number, number]} [width, height]
 */
export function rectFromDe(de, height) {
  if (de <= 0) return [0.0, 0.0];
  if (!height || height <= 0) {
    const side = de * 2.0 ** 0.25 / 1.30;
    return [side, side];
  }

  const h = Number(height);
  let w = Math.PI * de * de / 4.0 / h;          // equal-area seed
  for (let i = 0; i < 200; i++) {
    const wNext = (de * (h + w) ** 0.25 / 1.30) ** 1.6 / h;
    if (Math.abs(wNext - w) <= 1e-13 * Math.max(1.0, Math.abs(w))) {
      w = wNext;
      break;
    }
    w = wNext;
  }
  return [w, h];
}

// ---------------------------------------------------------------------------
// Pressure drop
// ---------------------------------------------------------------------------

/**
 * Round diameter (in.) carrying qCfm with `dropInWg` over `lengthFt`.
 *
 * Inverts the *same* Swamee-Jain / Darcy-Weisbach model that
 * `frictionFromRound` applies, so rate -> diameter -> rate round-trips
 * exactly. Rearranging Darcy-Weisbach with V = 4Q/(pi D^2):
 *
 *     hf = 8 f L Q^2 / (pi^2 g D^5)   ->   D = [8 f L Q^2 / (pi^2 g hf)]^0.2
 *
 * `f` depends on `D`, but D ~ f^0.2 makes this a strong contraction; it
 * converges to machine precision in a handful of passes.
 *
 * Workbook 'Worksheet' G9:H26. Through V1.25 the workbook instead used White's
 * explicit sizing solution here, which disagreed with the forward path by 0.8%
 * on metal and up to 7.9% on fabric duct.
 */
export function roundDiaFromFriction(qCfm, dropInWg, lengthFt, epsFt) {
  if (qCfm <= 0 || dropInWg <= 0 || lengthFt <= 0) return 0.0;
  const q = qCfm / 60.0;                                  // cfs
  // exact inverse of the forward path's constant chain
  const hf = dropInWg * 144.0 / PSI_TO_IN_WG / RHO;       // head, ft of air
  const konst = 8.0 * lengthFt * q * q / (Math.PI ** 2 * GC * hf);
  let d = (konst * 0.02) ** 0.2;                          // seed at f = 0.02
  for (let i = 0; i < 100; i++) {
    const v = 4 * q / (Math.PI * d * d);                  // ft/sec
    const re = d * RHO * v / (MU * GC);
    const f = 0.25 / Math.log10(epsFt / d / 3.75 + 5.74 / re ** 0.9) ** 2;
    const dNext = (konst * f) ** 0.2;
    if (Math.abs(dNext - d) <= 1e-14 * d) {
      d = dNext;
      break;
    }
    d = dNext;
  }
  return d * 12.0;
}

/** Velocity, fpm, in a round duct of `diaIn` carrying `qCfm`. */
export function velocityInRound(qCfm, diaIn) {
  if (diaIn <= 0) return 0.0;
  return 576.0 * qCfm / (Math.PI * diaIn ** 2);
}

/** Pressure drop, in. wg, over `lengthFt` of round duct; cells I31:I36. */
export function frictionFromRound(qCfm, diaIn, lengthFt, epsFt) {
  if (qCfm <= 0 || diaIn <= 0) return 0.0;
  const vFpm = velocityInRound(qCfm, diaIn);
  const g = vFpm * RHO / 60.0;                            // mass flux    (I31)
  const re = diaIn / 12.0 * g / MU / GC;                  // Reynolds     (I32)
  // Swamee-Jain. The workbook uses 3.75 where the published form has 3.7;
  // kept as-is so results match the spreadsheet.
  const f = 0.25 / Math.log10(epsFt / diaIn * 12.0 / 3.75
                              + 5.74 / re ** 0.9) ** 2;   // friction f   (I33)
  const hf = f * lengthFt * (vFpm / 60.0) ** 2 / 2.0 / (diaIn / 12.0) / GC; // (I34)
  return RHO * hf / 144.0 * PSI_TO_IN_WG;                 // in. wg   (I35,I36)
}

// ---------------------------------------------------------------------------
// Solver
// ---------------------------------------------------------------------------

/**
 * Size a duct. Every value in the result is in the unit system that was asked for.
 *
 * @param {number} airVolume   cfm (US) or l/s (Metric)
 * @param {string} criterion   which design criterion `value` supplies
 * @param {number} value       fpm | in.wg/100' | in. dia | in. width
 *                             (m/s | Pa/30 m | cm | cm)
 * @param {object} [opts]
 * @param {string} [opts.material=Material.METAL]
 * @param {string} [opts.units=Units.US]
 * @param {number} [opts.ductHeight]  duct height, in. | cm. For
 *   Criterion.RECT_WH it is the H of the given W x H; otherwise it constrains
 *   the rectangular result to that depth.
 */
export function solve(airVolume, criterion, value, opts = {}) {
  const { material = Material.METAL, units = Units.US, ductHeight = null } = opts;

  if (!Object.values(Units).includes(units)) throw new Error(`unknown units: ${units}`);
  if (!Object.values(Material).includes(material)) throw new Error(`unknown material: ${material}`);
  if (!Object.values(Criterion).includes(criterion)) throw new Error(`unknown criterion: ${criterion}`);

  const metric = units === Units.METRIC;
  const eps = ROUGHNESS_FT[material];

  // --- into internal US working units: cfm, in., fpm, in.wg per 100 ft ---
  const q = metric ? airVolume * CFM_PER_LPS : airVolume;
  let heightIn = (ductHeight || 0.0) * (metric ? IN_PER_M / 100.0 : 1.0);
  heightIn = heightIn > 0 ? heightIn : null;

  let vGiven = 0.0, diaGiven = 0.0, widthGiven = 0.0;
  let rate = 0.0;                                 // in. wg per 100 ft
  if (criterion === Criterion.AIR_VELOCITY) {
    vGiven = metric ? value * FPM_PER_MPS : value;
  } else if (criterion === Criterion.FRICTION_LOSS) {
    // Metric input is Pa per 30 m -> in. wg per 100 ft.
    rate = metric
      ? value / PA_PER_IN_WG * (BASIS_FT / (BASIS_M * FT_PER_M))
      : value;
  } else if (criterion === Criterion.ROUND_DIA) {
    diaGiven = metric ? value * IN_PER_M / 100.0 : value;
  } else {
    widthGiven = metric ? value * IN_PER_M / 100.0 : value;
  }

  // --- the round duct is the primary answer -----------------------------
  let dia;
  if (criterion === Criterion.AIR_VELOCITY) {
    dia = (vGiven > 0 && q > 0)
      ? Math.sqrt(4 * q / vGiven * 144 / Math.PI)
      : 0.0;
  } else if (criterion === Criterion.FRICTION_LOSS) {
    dia = roundDiaFromFriction(q, rate, BASIS_FT, eps);
  } else if (criterion === Criterion.ROUND_DIA) {
    dia = diaGiven;
  } else {
    dia = huebscherDe(widthGiven, heightIn || widthGiven);
  }

  // --- friction rate ----------------------------------------------------
  if (criterion !== Criterion.FRICTION_LOSS) {
    rate = frictionFromRound(q, dia, BASIS_FT, eps);
  }

  // --- the equal-friction rectangle -------------------------------------
  let rectW, rectH;
  if (criterion === Criterion.RECT_WH) {
    rectW = widthGiven;
    rectH = heightIn || widthGiven;
  } else {
    [rectW, rectH] = rectFromDe(dia, heightIn);
  }

  const vRound = velocityInRound(q, dia);
  const vRect = (rectW > 0 && rectH > 0) ? 144.0 * q / (rectW * rectH) : 0.0;

  // --- back into the requested unit system ------------------------------
  if (metric) {
    return {
      units, material,
      length: BASIS_M,
      airVolume: q / CFM_PER_LPS,
      velocityRound: vRound / FPM_PER_MPS,
      velocityRect: vRect / FPM_PER_MPS,
      pressureDrop: rate * PA_PER_IN_WG * (BASIS_M * FT_PER_M / BASIS_FT),
      roundDia: dia / IN_PER_M * 100.0,
      rectWidth: rectW / IN_PER_M * 100.0,
      rectHeight: rectH / IN_PER_M * 100.0,
    };
  }
  return {
    units, material,
    length: BASIS_FT,
    airVolume: q,
    velocityRound: vRound,
    velocityRect: vRect,
    pressureDrop: rate,
    roundDia: dia,
    rectWidth: rectW,
    rectHeight: rectH,
  };
}

/** Free area of the rectangle, in^2 | cm^2. */
export function rectArea(r) { return r.rectWidth * r.rectHeight; }

/** Free area of the round duct, in^2 | cm^2. */
export function roundArea(r) { return Math.PI * r.roundDia ** 2 / 4.0; }

// ---------------------------------------------------------------------------
// Presentation — mirrors the published calculator's Results table
// ---------------------------------------------------------------------------

/**
 * The friction rate, written to the precision the number actually carries.
 *
 * Three decimals of in. wg per 100 ft is about a quarter of a Pa per 30 m, so
 * carrying three decimals into the metric display would show a resolution
 * nothing in the calculation has. One decimal on Pa is the same precision, not
 * less of it.
 *
 * Python's format_result prints three in both systems; this is the one place
 * the two deliberately differ, and it is display only — solve() is untouched
 * and the reference grid still matches to the last bit.
 */
export function formatDrop(r) {
  return r.pressureDrop.toFixed(r.units === Units.METRIC ? 1 : 3);
}

/** The results table as label / value / unit rows, formatted for display. */
export function resultRows(r) {
  const metric = r.units === Units.METRIC;
  const lengthU = metric ? 'm' : 'ft';
  const volU = metric ? 'l/s' : 'cfm';
  const velU = metric ? 'm/s' : 'fpm';
  const dropU = metric ? 'Pa/30 m' : "in. wg/100'";
  const dimU = metric ? 'cm' : 'in.';
  const group = n => n.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 0 });
  const vel = x => (metric
    ? x.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    : group(x));

  return [
    ['Length', group(r.length), lengthU],
    ['Air Volume', group(r.airVolume), volU],
    ['Air Velocity, Round', vel(r.velocityRound), velU],
    ['Pressure Drop', formatDrop(r), dropU],
    ['Round Duct', r.roundDia.toFixed(2), `${dimU} (Diameter)`],
    ['Rect. Duct', r.rectWidth.toFixed(2), `${dimU} (Width)`],
    ['Rect. Duct', r.rectHeight.toFixed(2), `${dimU} (Height)`],
    ['Air Velocity, Rect.', vel(r.velocityRect), velU],
  ];
}
