// Build src/assets/js/ashrae621-tables.js from the ASHRAE 62.1-2025 capture in
// calc-cases/sources/ashrae-62.1-2025-tables.json. The page never reads the
// source; this writes it out in the shape the calculator uses, and
// check-ventilation-tables.mjs (run by npm test) holds the result to the source.
//
//   node tools/extract/build-ashrae621-tables.mjs
import fs from 'node:fs';

const src = JSON.parse(fs.readFileSync('calc-cases/sources/ashrae-62.1-2025-tables.json', 'utf8'));

// Numbers as numbers; "—" (not applicable) and "NA" as printed; a blank cell as null.
export const cellOf = v => (v === '' ? null : /^\d+(\.\d+)?$/.test(v) ? Number(v) : v);

// Table 6-2 rows that are the same space as a Table 6-1 category, under the
// Table 6-1 name, so the page shows both for one choice. The rest are their own
// categories, as the standard lists them.
export const SAME_SPACE = {
  'Art classrooms': 'Educational Facilities-Art classroom',
  'Barber shops': 'Retail-Barbershop',
  'Beauty and nail salons': 'Retail-Beauty and nail salons',
  'Cells with toilet': 'Correctional Facilities-Cell',
  'Pet shops (animal areas)': 'Retail-Pet shops (animal areas)',
  'Science laboratories': 'Educational Facilities-Science laboratories',
};
export const name62 = r => (r.group ? `${r.group}-${r.name}` : SAME_SPACE[r.name] ?? r.name);

export function build() {
  const t61 = [
    ...src.table61.map(r => [`${r.group}-${r.name}`, ...r.values.slice(0, 6).map(cellOf), cellOf(r.values[6]), r.os]),
    ...src.tableE1.map(r => [`Outpatient Health Care Facilities-${r.name}`, ...r.values.map(cellOf), 'NA', r.os]),
  ];
  // Continuous and intermittent rates are kept as the standard pairs them,
  // continuous first: "50/100" cfm per unit.
  const t62 = src.table62.map(r => {
    const [cfmUnit, cfmArea, lsUnit, lsArea, cls] = r.values.map(cellOf);
    if (!r.modes.length) return [name62(r), cfmUnit, cfmArea, lsUnit, lsArea, cls];
    const [c, i] = ['Continuous', 'Intermittent'].map(m => r.modes.find(x => x.mode === m));
    return [name62(r), `${c.cfmUnit}/${i.cfmUnit}`, cfmArea, `${c.lsUnit}/${i.lsUnit}`, lsArea, cls];
  });
  return { t61, t62 };
}

if (process.argv[1]?.endsWith('build-ashrae621-tables.mjs')) {
  const { t61, t62 } = build();
  const js = `// ANSI/ASHRAE Standard 62.1-2025 Table 6-1 (minimum ventilation rates in the
// breathing zone), Normative Appendix E Table E-1 (outpatient health care
// facilities not covered by Standard 170) and Table 6-2 (minimum exhaust rates).
// Generated by tools/extract/build-ashrae621-tables.mjs from
// calc-cases/sources/ashrae-62.1-2025-tables.json; do not edit by hand.
// "—" is the standard's "not applicable"; null is a cell the standard leaves blank.

// [occupancy category, Rp cfm/person, Rp L/s·person, Ra cfm/ft², Ra L/s·m²,
//  default occupant density #/1000 ft² (#/100 m²), air class,
//  maximum CO2 above ambient ΔC6.1 (ppm, or "NA"), occupied-standby (OS) allowed]
// Table E-1 has no CO2 column; its rows carry "NA".
export const TABLE_6_1 = ${JSON.stringify(t61)};

// [occupancy category, cfm/unit, cfm/ft², L/s·unit, L/s·m², air class]
// A per-unit pair such as "50/100" is continuous / intermittent operation.
export const TABLE_6_2 = ${JSON.stringify(t62)};
`;
  fs.writeFileSync('src/assets/js/ashrae621-tables.js', js);
  console.log(`Table 6-1 + E-1: ${t61.length} rows; Table 6-2: ${t62.length} rows -> src/assets/js/ashrae621-tables.js`);
}
