// Build src/assets/js/ventilation-tables.js from the tables captured in
// calc-cases/sources. The page never reads the sources; this writes them out in
// the shape the calculator uses, and check-ventilation-tables.mjs (run by npm
// test) holds the result to the sources.
//
//   node tools/extract/build-ventilation-tables.mjs
import fs from 'node:fs';

const src = f => JSON.parse(fs.readFileSync(`calc-cases/sources/${f}`, 'utf8'));
const imc = src('imc-2024-table-403.3.1.1.json').rows;
const fbc23 = src('fbc-mechanical-2023-table-403.3.1.1.json').rows;
const t71 = src('ashrae-170-2021-table-7-1.json').rows;

// Words the 170 PDF broke across lines, and its one garbled heading.
const REPAIR = [[/tr auma/, 'trauma'], [/recove ry/, 'recovery'], [/ar ea/, 'area'], [/L a boratory/, 'Laboratory'],
  [/ster ile/, 'sterile'], [/medical\/ surgical/, 'medical/surgical'], [/OTH & ER/, 'OTHER']];
const repair = s => REPAIR.reduce((t, [re, to]) => t.replace(re, to), s);
const title = s => repair(s).toLowerCase().replace(/(^|[\s:(/-])([a-z])/g, (m, p, c) => p + c.toUpperCase())
  .replace(/\b(And|For|Of|Or|The)\b/g, w => w.toLowerCase());

const NOTE = /\(([a-z]{1,2})\)/g;
const letters = s => [...(s ?? '').matchAll(NOTE)].map(m => m[1]);
// One value column: the value, then any notes on it.
const COL = String.raw`((?:Max|Min) \d+(?:\/\d+)?|\(e\)|[^\s(]+)((?:,?\s*\([a-z]{1,2}\))*)`;
const VALUES = new RegExp(`^${Array(9).fill(COL).join(String.raw`\s+`)}$`);

const ashrae170 = t71.map(r => {
  const m = VALUES.exec(r.values);
  if (!m) throw new Error(`170: cannot split the values of ${r.name}: ${r.values}`);
  const cols = [];
  for (let i = 0; i < 9; i++) cols.push({ v: m[1 + 2 * i], n: letters(m[2 + 2 * i]) });
  let name = repair(r.name);
  const fgi = [...name.matchAll(/\((?:FGI |Table )[^()]*(?:\([^()]*\)[^()]*)*\)/g)].map(x => x[0].slice(1, -1));
  const rowNotes = letters(name.replace(/\((?:FGI |Table )[^()]*(?:\([^()]*\)[^()]*)*\)/g, ''));
  name = name.replace(/\s*\((?:FGI |Table )[^()]*(?:\([^()]*\)[^()]*)*\)/g, '').replace(/(\s*,?\s*\([a-z]{1,2}\))+\s*$/, '').trim();
  // "(e)" in the pressure column means "see note e"; N/R is the table's other spelling of NR.
  const clean = c => ({ v: c.v === '(e)' ? 'See note e' : c.v === 'N/R' ? 'NR' : c.v.replace(/(\d)-(\d)/g, '$1–$2'), n: c.v === '(e)' ? ['e', ...c.n] : c.n });
  const [pressure, oa, total, exhausted, recirc, turndown, filter, rh, temp] = cols.map(clean);
  return { group: title(r.heading), name, fgi: fgi.join('; '), notes: rowNotes, pressure, oa, total, exhausted, recirc, turndown, filter, rh, temp };
});

const js = `// GENERATED by tools/extract/build-ventilation-tables.mjs from calc-cases/sources.
// Do not edit: fix the source (or the generator) and rebuild. npm test checks
// this file against the sources.

// 2024 IMC Table 403.3.1.1 (also the 2026 FBC-Mechanical, Ninth Edition, table).
// [group, occupancy, note letters, density #/1000 ft², Rp cfm/person, Ra cfm/ft²,
//  exhaust cfm/ft², or cfm per room or fixture ("25/50") where a note says so]
export const IMC_2024 = ${JSON.stringify(imc)};

// 2023 FBC-Mechanical, Eighth Edition, Table 403.3.1.1, same columns.
export const FBC_2023 = ${JSON.stringify(fbc23)};

// ANSI/ASHRAE/ASHE 170-2021 Table 7-1, inpatient spaces. Each value is
// { v: as printed, n: [note letters] }; NR = no requirement.
export const ASHRAE_170 = ${JSON.stringify(ashrae170)};
`;
fs.writeFileSync('src/assets/js/ventilation-tables.js', js);
console.log(`IMC ${imc.length}, FBC 2023 ${fbc23.length}, 170 ${ashrae170.length} rows`);
