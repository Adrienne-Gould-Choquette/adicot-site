// Build src/assets/js/cooling-hours.js from calc-cases/sources/energystar-full-load-hours.tsv.
// check-handworked.mjs (npm test) holds the result to the source.
//
//   node tools/extract/build-cooling-hours.mjs
import fs from 'node:fs';

// City names as spelled locally; the ENERGY STAR sheet has these two wrong.
const SPELLING = { 'MI-Sault St Marie': 'MI-Sault Ste. Marie', 'MT-Miles city': 'MT-Miles City' };

export const readHours = () => fs.readFileSync('calc-cases/sources/energystar-full-load-hours.tsv', 'utf8')
  .split(/\r?\n/).filter(l => l && !l.startsWith('#')).map(l => { const [city, cool] = l.split('\t'); return [SPELLING[city] ?? city, Number(cool)]; });

if (process.argv[1]?.endsWith('build-cooling-hours.mjs')) {
  fs.writeFileSync('src/assets/js/cooling-hours.js', `// GENERATED by tools/extract/build-cooling-hours.mjs from calc-cases/sources.
// Do not edit: fix the source (or the generator) and rebuild.
//
// Equivalent full-load cooling hours by city: ENERGY STAR's air-source heat pump
// savings calculator (ASHP_Sav_Calc.xls), data source EPA 2002. [city, hours]
export const COOLING_HOURS = ${JSON.stringify(readHours())};
`);
  console.log('written');
}
